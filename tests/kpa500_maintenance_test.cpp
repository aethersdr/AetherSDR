QByteArray withChecksum(QByteArray contents)
{
    const qsizetype trailer = contents.indexOf("CRC32 = ");
    if (trailer >= 0) {
        contents.truncate(trailer);
    }
    std::array<quint32, 256> table{};
    for (quint32 index = 0; index < table.size(); ++index) {
        quint32 value = index;
        for (int bit = 0; bit < 8; ++bit) {
            value = (value >> 1) ^ ((value & 1U) != 0U ? 0xedb88320U : 0U);
        }
        table[index] = value;
    }
    quint32 crc = 0xffffffffU;
    for (const char byte : contents) {
        if (byte != '\r' && byte != '\n') {
            crc = (crc >> 8) ^ table[(crc ^ static_cast<quint8>(byte)) & 0xffU];
        }
    }
    return contents + "CRC32 = 0x" + QByteArray::number(crc, 16).rightJustified(8, '0').toUpper() + "\r\n";
}

QByteArray modified(const QByteArray& before, const QByteArray& after)
{
    QByteArray result = kCapturedBackup;
    result.replace(before, after);
    return withChecksum(result);
}

QString replyArgument(quint16 address, int length, const QByteArray& data)
{
    QByteArray bytes;
    bytes.append(static_cast<char>(address >> 8));
    bytes.append(static_cast<char>(address & 0xff));
    bytes.append(static_cast<char>(length));
    bytes += data;
    int sum = 0;
    for (const char byte : bytes) {
        sum += static_cast<quint8>(byte);
    }
    bytes.append(static_cast<char>((-sum) & 0xff));
    return QString::fromLatin1(bytes.toHex().toUpper());
}

void rejectFile(const char* name, const QByteArray& contents)
{
    QString error;
    report(name, !decodeConfigurationBackup(contents, &error) && !error.isEmpty());
}

