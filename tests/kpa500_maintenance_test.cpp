int main()
{
    report("captured EEPROM read commands", buildEepromRead(0, 64) == "^ER000040C0;"
           && buildEepromRead(64, 64) == "^ER00404080;"
           && buildEepromRead(128, 64) == "^ER00804040;"
           && buildEepromRead(192, 32) == "^ER00C02020;"
           && buildEepromRead(0x50, 8) == "^ER005008A8;");
    report("read accepts final memory byte", buildEepromRead(1023, 1) == "^ER03FF01FD;");
    report("read rejects zero, negative, oversized and overflowing ranges",
           buildEepromRead(0, 0).isEmpty() && buildEepromRead(0, -1).isEmpty()
           && buildEepromRead(0, 65).isEmpty() && buildEepromRead(0, std::numeric_limits<int>::max()).isEmpty()
           && buildEepromRead(1023, 2).isEmpty() && buildEepromRead(1024, 1).isEmpty()
           && buildEepromRead(65535, 1).isEmpty());
    report("captured banner write includes NUL and checksum",
           buildEepromWrite(0x50, QByteArray("LABTEST1\0", 9)) == "^EW0050094C414254455354310067;");
    report("write accepts final config byte", buildEepromWrite(223, QByteArray(1, char(0xff))) == "^EW00DF01FF21;");
    report("write rejects non-config memory and invalid sizes",
           buildEepromWrite(224, "A").isEmpty() && buildEepromWrite(223, "AB").isEmpty()
           && buildEepromWrite(0, {}).isEmpty() && buildEepromWrite(0, QByteArray(65, 'A')).isEmpty()
           && buildEepromWrite(65535, "A").isEmpty());

    const std::optional<EepromReply> banner = parseEepromReply("ER", "00500853494D3132333435C0");
    report("captured read reply", banner && banner->address == 0x50 && banner->length == 8
           && banner->data == "SIM12345" && !banner->writeAck);
    const std::optional<EepromReply> ack = parseEepromReply("EW", "005009A7");
    report("captured write ack", ack && ack->address == 0x50 && ack->length == 9
           && ack->data.isEmpty() && ack->writeAck);
    report("ASCII command and hex case accepted", parseEepromReply("er", "00500853494d3132333435c0").has_value());
    report("reply checksum tamper rejected", !parseEepromReply("ER", "00500853494D3132333435C1"));
    report("unknown command and wire decorations rejected", !parseEepromReply("FL", "005009A7")
           && !parseEepromReply("^EW", "005009A7") && !parseEepromReply("EW", "005009A7;"));
    report("truncated, odd, nonhex, whitespace and Unicode rejected",
           !parseEepromReply("EW", "00") && !parseEepromReply("EW", "005009A")
           && !parseEepromReply("EW", "005009G7") && !parseEepromReply("EW", "005009 A7")
           && !parseEepromReply("EW", QString::fromUtf8("005009\xEF\xBC\xA1" "7")));
    report("read length must match data exactly", !parseEepromReply("ER", replyArgument(0x50, 8, "SHORT"))
           && !parseEepromReply("ER", replyArgument(0x50, 8, "TOO LONG!")));
    report("write ack cannot contain payload", !parseEepromReply("EW", replyArgument(0x50, 1, "A")));
    report("invalid reply bounds rejected", !parseEepromReply("ER", replyArgument(0, 0, {}))
           && !parseEepromReply("ER", replyArgument(0, 65, QByteArray(65, '\0')))
           && !parseEepromReply("ER", replyArgument(1023, 2, "AB"))
           && !parseEepromReply("ER", replyArgument(65535, 1, "A"))
           && !parseEepromReply("EW", replyArgument(224, 1, {})));
    QByteArray binaryData;
    for (int value = 192; value <= 255; ++value) {
        binaryData.append(static_cast<char>(value));
    }
    const std::optional<EepromReply> binary = parseEepromReply("ER", replyArgument(960, 64, binaryData));
    report("maximum reply preserves high-bit bytes", binary && binary->data == binaryData);

    QString error = QStringLiteral("stale error");
    const std::optional<ConfigurationBackup> captured = decodeConfigurationBackup(kCapturedBackup, &error);
    QByteArray expectedData(224, '\0');
    expectedData.replace(0x50, 8, "SIM12345");
    report("observed native export decodes and clears error", captured && error.isEmpty()
           && captured->data == expectedData && captured->firmware == "01.54" && captured->serial == "09999");
    const std::optional<ConfigurationBackup> second = decodeConfigurationBackup(kSecondBackup);
    report("independent second native export CRC validates", second && second->data.mid(0x50, 8) == "SECOND42");
    report("fixture checksum independent helper agrees", withChecksum(kCapturedBackup) == kCapturedBackup);
    QByteArray lf = kCapturedBackup;
    lf.replace("\r\n", "\n");
    report("LF and CRLF use identical checksum coverage", decodeConfigurationBackup(lf).has_value());
    const QDateTime savedAt(QDate(2026, 10, 12), QTime(21, 32, 10));
    const ConfigurationBackup backup{expectedData, QStringLiteral("01.54"), QStringLiteral("09999")};
    const QByteArray encoded = encodeConfigurationBackup(backup, savedAt);
    const std::optional<ConfigurationBackup> roundtrip = decodeConfigurationBackup(encoded);
    report("encoder roundtrips identity and all bytes", roundtrip && roundtrip->data == backup.data
           && roundtrip->firmware == backup.firmware && roundtrip->serial == backup.serial);
    report("encoder identifies AetherSDR truthfully", encoded.contains("KPA Utility Revision = AetherSDR\r\n")
           && !encoded.contains("Elecraft KPA Utility Revision"));
    report("encoder matches captured file with truthful utility label and new CRC",
           encoded == modified("KPA Utility Revision = Elecraft KPA Utility Revision 1.13.7.16",
                               "KPA Utility Revision = AetherSDR"));
    report("invalid encoding input fails closed", encodeConfigurationBackup({QByteArray(223, '\0'), "01.54", "09999"}, savedAt).isEmpty()
           && encodeConfigurationBackup({expectedData, "1.54", "09999"}, savedAt).isEmpty()
           && encodeConfigurationBackup({expectedData, "01.54", "9999"}, savedAt).isEmpty()
           && encodeConfigurationBackup(backup, {}).isEmpty());

    rejectFile("empty file rejected", {});
    rejectFile("file size capped", QByteArray(65537, '*'));
    QByteArray tampered = kCapturedBackup;
    tampered.replace("09999", "09998");
    rejectFile("one-byte header tamper rejected", tampered);
    tampered = kCapturedBackup;
    tampered.replace("53494D3132333435", "53494D3132333434");
    rejectFile("one-byte memory tamper rejected", tampered);
    tampered = kCapturedBackup;
    tampered.replace("21:32:10", "21:32:11");
    rejectFile("comment timestamp participates in checksum", tampered);
    rejectFile("missing checksum rejected", kCapturedBackup.left(kCapturedBackup.indexOf("CRC32")));
    rejectFile("invalid checksum hex rejected", QByteArray(kCapturedBackup).replace("47C504E5", "47C504G5"));
    rejectFile("duplicate checksum rejected", kCapturedBackup + "CRC32 = 0x47C504E5\r\n");
    rejectFile("records after checksum rejected", kCapturedBackup + "*extra\r\n");
    rejectFile("unknown record rejected", modified("*Do not edit this file!", "UNKNOWN = value"));
    rejectFile("missing serial rejected", modified("KPA Serial Number = 09999\r\n", ""));
    rejectFile("duplicate serial rejected", modified("KPA Serial Number = 09999", "KPA Serial Number = 09999\r\nKPA Serial Number = 09999"));
    rejectFile("duplicate firmware rejected", modified("KPA Firmware Revision = 01.54", "KPA Firmware Revision = 01.54\r\nKPA Firmware Revision = 01.54"));
    rejectFile("duplicate utility rejected", modified("KPA Utility Revision = ", "KPA Utility Revision = AetherSDR\r\nKPA Utility Revision = "));
    rejectFile("malformed serial rejected despite valid CRC", modified("KPA Serial Number = 09999", "KPA Serial Number = 0999X"));
    rejectFile("malformed firmware rejected despite valid CRC", modified("KPA Firmware Revision = 01.54", "KPA Firmware Revision = 1.54"));
    rejectFile("empty utility rejected despite valid CRC", modified("KPA Utility Revision = Elecraft KPA Utility Revision 1.13.7.16", "KPA Utility Revision = "));
    rejectFile("blank utility rejected despite valid CRC", modified("KPA Utility Revision = Elecraft KPA Utility Revision 1.13.7.16", "KPA Utility Revision =   "));
    rejectFile("bare trailing carriage return rejected", kCapturedBackup.left(kCapturedBackup.size() - 1));
    rejectFile("nonhex memory rejected despite valid CRC", modified("53494D3132333435", "53494G3132333435"));
    rejectFile("wrong record count rejected", modified("MEM2 00 40 20", "MEM2 00 40 1F"));
    rejectFile("overlapping records rejected", modified("MEM2 00 20 20", "MEM2 00 00 20"));
    rejectFile("unaligned record rejected", modified("MEM2 00 20 20", "MEM2 00 01 20"));
    rejectFile("record outside config rejected", modified("MEM2 00 C0 20", "MEM2 00 E0 20"));
    rejectFile("large record address rejected", modified("MEM2 00 C0 20", "MEM2 FF E0 20"));
    const QByteArray firstRecord = "MEM2 00 00 20 " + QByteArray(64, '0') + "\r\n";
    rejectFile("missing memory record rejected", modified(firstRecord, ""));
    rejectFile("extra duplicate memory record rejected", modified(firstRecord, firstRecord + firstRecord));
    rejectFile("embedded control character rejected", modified("*Do not edit", QByteArray("*Do\0not edit", 12)));
    rejectFile("embedded carriage return rejected", modified("*Do not edit", "*Do\rnot edit"));
    rejectFile("tab rejected", modified("*Do not edit", "*Do\tnot edit"));
    rejectFile("oversized comment rejected", modified("*Do not edit this file!", '*' + QByteArray(512, 'a')));
    report("printable comments allowed and checksummed", decodeConfigurationBackup(modified("*Do not edit this file!", "*Additional comment with  two spaces ")).has_value());
    report("future numeric firmware accepted by codec", decodeConfigurationBackup(modified("KPA Firmware Revision = 01.54", "KPA Firmware Revision = 02.01")).has_value());

    return g_failed == 0 ? 0 : 1;
}
